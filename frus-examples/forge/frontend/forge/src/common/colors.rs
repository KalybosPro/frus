use frus::Color;

// 00C950
pub(crate) fn primary_color() -> Color {
    Color::hex("#00C950")
}

pub(crate) fn black() -> Color {
    Color::hex("#09090B")
}

pub(crate) fn grey() -> Color {
    Color::hex("#71717B")
}

pub(crate) fn white() -> Color {
    Color::hex("#F0FDF4")
}

pub(crate) fn gray() -> Color{
    Color::hex("#E4E4E7")
}

pub(crate) fn light_gray() -> Color{
    Color::hex("#F4F4F5")
}
